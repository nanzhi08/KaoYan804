async def seed():
    await init_db()

    async with async_session() as session:
        # 查找所有章节知识点
        result = await session.execute(
            select(KnowledgePoint).where(KnowledgePoint.chapter != "")
        )
        chapter_kps = {kp.chapter: kp for kp in result.scalars().all()}

        total = 0
        for chapter, details in DETAIL_KNOWLEDGE.items():
            parent = chapter_kps.get(chapter)
            if not parent:
                print(f"  Warning: 找不到章节 {chapter}，跳过。")
                continue

            # 检查是否已有子节点
            child_result = await session.execute(
                select(KnowledgePoint).where(KnowledgePoint.parent_id == parent.id).limit(1)
            )
            if child_result.scalars().first():
                print(f"  {chapter} 已有子知识点，跳过。")
                continue

            for i, (name, desc, difficulty, weight) in enumerate(details):
                child = KnowledgePoint(
                    name=f"{chapter} - {name}",
                    part=parent.part,
                    chapter=chapter,
                    description=desc,
                    difficulty=difficulty,
                    exam_weight=weight,
                    parent_id=parent.id,
                    order=i,
                )
                session.add(child)
                await session.flush()

                # 创建掌握度记录
                mastery = KnowledgeMastery(knowledge_point_id=child.id)
                session.add(mastery)

                total += 1

        await session.commit()
        print(f"知识点扩展完成！新增 {total} 个详细知识子节点。")
        print(f"C语言: {sum(len(v) for k,v in DETAIL_KNOWLEDGE.items() if k.startswith('1.'))} 个子节点")
        print(f"数据结构: {sum(len(v) for k,v in DETAIL_KNOWLEDGE.items() if k.startswith('2.'))} 个子节点")
        print("涵盖16个章节，每个章节4-13个详细知识点。")


if __name__ == "__main__":
    asyncio.run(seed())
