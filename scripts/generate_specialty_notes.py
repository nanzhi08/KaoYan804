    lines.append(f"- 考频判断：{exam_weight}")
    if q_types:
        lines.append(f"- 常见题型：{'、'.join(q_types)}")
    for ctx in note_info["contexts"][:4]:
        lines.append(f"- 教材定位：{ctx['subject']} · {ctx['chapter']} · {ctx['label']}")
    return lines


