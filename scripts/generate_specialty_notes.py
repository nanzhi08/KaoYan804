def sanitize_filename(name: str) -> str:
    return re.sub(r'[<>:"/\\\\|?*]', "_", name)


def link(name: str) -> str:
    return f"[[{name}]]"


def parse_moc(path: Path) -> tuple[str, str, str, list[Chapter]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    title = lines[0].strip()
    textbook = ""
    intro = ""
    chapters: list[Chapter] = []
    current: Chapter | None = None
    for line in lines[1:]:
        stripped = line.strip()
        if stripped.startswith("教材："):
            textbook = stripped
            continue
        if stripped.startswith("按教材知识内容拆分"):
            intro = stripped
            continue
        if stripped.startswith("## "):
            current = Chapter(title=stripped[3:].strip(), bullets=[])
            chapters.append(current)
            continue
        if stripped.startswith("- ") and current is not None:
            match = re.match(r"-\s*(.+?)：(.+)", stripped)
            if not match:
                continue
            label = match.group(1).strip()
            concepts = re.findall(r"\[\[([^\]]+)\]\]", match.group(2))
            current.bullets.append(Bullet(label=label, concepts=concepts))
    return title, textbook, intro, chapters


def enrich_chapters(file_name: str, chapters: list[Chapter]) -> list[Chapter]:
    extra = EXTRA_BULLETS.get(file_name, {})
    enriched: list[Chapter] = []
    for chapter in chapters:
        bullets = list(chapter.bullets)
        for label, concepts in extra.get(chapter.title, []):
            if not any(b.label == label for b in bullets):
                bullets.append(Bullet(label=label, concepts=concepts))
        enriched.append(Chapter(title=chapter.title, bullets=bullets))
    return enriched


def write_moc(path: Path, title: str, textbook: str, intro: str, chapters: list[Chapter]) -> None:
    lines = [title, "", textbook, "", intro, ""]
    for chapter in chapters:
        lines.append(f"## {chapter.title}")
        lines.append("")
        for bullet in chapter.bullets:
            concept_links = "、".join(link(c) for c in bullet.concepts)
            lines.append(f"- {bullet.label}：{concept_links}")
        lines.append("")
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def collect_concepts(chapters_by_file: dict[str, list[Chapter]]) -> dict[str, dict]:
    notes: dict[str, dict] = defaultdict(lambda: {"contexts": [], "subjects": set(), "children": set(), "parents": set()})
    for file_name, chapters in chapters_by_file.items():
        subject = MOC_FILES[file_name]
        for chapter in chapters:
            chapter_concepts = [concept for bullet in chapter.bullets for concept in bullet.concepts]
            for bullet in chapter.bullets:
                for concept in bullet.concepts:
                    notes[concept]["contexts"].append(
                        {
                            "subject": subject,
                            "chapter": chapter.title,
                            "label": bullet.label,
                            "peers": [c for c in bullet.concepts if c != concept],
                            "chapter_peers": [c for c in chapter_concepts if c != concept],
                        }
                    )
                    notes[concept]["subjects"].add(subject)
    for parent, children in EXPANDED_CONCEPTS.items():
        if parent in notes:
            for child in children:
                notes[parent]["children"].add(child)
                notes[child]["parents"].add(parent)
    return notes


