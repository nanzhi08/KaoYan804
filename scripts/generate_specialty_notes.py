def build_context_lines(note_info: dict) -> list[str]:
    subjects = sorted(note_info["subjects"])
    lines = [f"- 学科：{' / '.join(subjects)}"]
    locations = []
    for ctx in note_info["contexts"]:
        locations.append(f"{ctx['subject']} · {ctx['chapter']} · {ctx['label']}")
    seen = []
    for item in locations:
        if item not in seen:
            seen.append(item)
    for loc in seen[:6]:
        lines.append(f"- 定位：{loc}")
    return lines


