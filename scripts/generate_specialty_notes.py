def build_front_knowledge(concept: str, note_info: dict) -> list[str]:
    related = pick_related(concept, note_info, limit=8)
    children = sorted(note_info["children"])
    parents = sorted(note_info["parents"])
    result: list[str] = []
    for item in parents + children + related:
        if item != concept and item not in result:
            result.append(item)
    return result[:6]


def detect_suffix(concept: str) -> tuple[str | None, str | None]:
    for suffix in OPERATION_SUFFIXES:
        if concept.endswith(suffix) and len(concept) > len(suffix):
            return concept[: -len(suffix)], suffix
    return None, None


